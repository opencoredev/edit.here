/** FNV-1a over the file list; changes whenever any hashed asset changes. */
function hashString(input: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(36);
}

/**
 * Emits `sw.js`, which precaches every built file on the first visit so both editors open with
 * the network off, plus the fonts and icon copied from `public/` (fonts that load only at idle or
 * when a rare glyph shows would otherwise be missing offline). The precache list and cache name
 * are baked into the file, so each deploy ships a byte-different worker and replaces the old cache.
 */
function offlineServiceWorker(): Plugin {
  let publicDir = "";
  return {
    name: "edit-here-offline-sw",
    apply: "build",
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle)
        .filter((name) => !name.endsWith(".map"))
        .toSorted();
      const publicFiles =
        publicDir === ""
          ? []
          : readdirSync(publicDir, { recursive: true, encoding: "utf8" })
              .map((name) => name.split(path.sep).join("/"))
              .filter((name) => /\.(woff2|svg)$/.test(name))
              .toSorted();
      const precache = ["/", ...[...files, ...publicFiles].map((name) => `/${name}`)];
      // Public files keep their names across deploys, so their bytes go into the cache name.
      const publicHash = publicFiles
        .map((name) => hashString(readFileSync(path.join(publicDir, name), "latin1")))
        .join(",");
      const cacheName = `edit-here-${hashString(`${files.join("\n")}\n${publicHash}`)}`;
      const source = `// Generated by vite.config.ts (edit-here-offline-sw). Nothing here sends data anywhere.
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};

// addAll is all-or-nothing, so this build's page and every asset it references land in its
// cache together, or the install fails and the previous build keeps serving.
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

// Keep the previous build's cache too: tabs still running it lazy-load their editor chunks
// from there after this worker takes over. Anything older is deleted.
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => {
        const older = keys.filter((key) => key.startsWith("edit-here-") && key !== CACHE);
        return Promise.all(older.slice(0, -1).map((key) => caches.delete(key)));
      })
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    // Network first so a new deploy shows up. Offline, serve the page precached with this
    // build's assets; it is never overwritten here, so page and assets always match.
    event.respondWith(
      fetch(request).catch(() =>
        caches.match("/", { cacheName: CACHE }).then((hit) => hit ?? Response.error()),
      ),
    );
    return;
  }

  // This build's cache first: fonts and the favicon keep their URLs across deploys, so an older
  // cache can hold different bytes for them. Older caches still answer for the hashed chunks of
  // tabs running a previous build. Anything else is cached the first time it loads.
  event.respondWith(
    caches
      .match(request, { cacheName: CACHE })
      .then((hit) => hit ?? caches.match(request))
      .then(
        (hit) =>
          hit ??
          fetch(request).then((response) => {
            if (response.ok && response.type === "basic") {
              const copy = response.clone();
              void caches.open(CACHE).then((cache) => cache.put(request, copy));
            }
            return response;
          }),
      ),
  );
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

/**
 * `motion/react` is a re-export of framer-motion, except that it binds `motion` and `m` to local
 * constants (`const motion = fm.motion`). Editors import `motion`, so that wrapper keeps the full
 * `motion` component (drag, layout projection, every animation feature) in whatever chunk Home
 * shares with them. Resolving `motion/react` straight to framer-motion's own ESM entry gives the
 * same exports with plain re-exports, so Home's `m` components load without the rest.
 */
const motionDir = path.dirname(require.resolve("motion/package.json"));
const framerMotionEntry = path.join(
  path.dirname(
    createRequire(path.join(motionDir, "package.json")).resolve("framer-motion/package.json"),
  ),
  "dist/es/index.mjs",
);

export default defineConfig({
  plugins: [react(), tailwindcss(), offlineServiceWorker()],
  resolve: {
    alias: [{ find: /^motion\/react$/, replacement: framerMotionEntry }],
  },
  server: {
    host: true,
    port: 5173,
  },
  build: {
    target: "es2022",
    sourcemap: true,
    rolldownOptions: {
      treeshake: {
        // The vendored Graphical library builds every component family at module top level
        // (components/graphical/components/library/{primitives,consumer}.tsx). These helpers
        // only wrap their arguments, so families nothing renders (and their Base UI code) drop.
        manualPureFunctions: ["themeFamily", "themeStatics", "themePart", "themeContainer"],
        // Its modules only define components (styles come from app.css), so a module whose
        // exports nothing uses is skipped even when it has top-level calls like createContext.
        moduleSideEffects: (id) => (id.includes("/src/components/graphical/") ? false : undefined),
      },
    },
  },
  worker: {
    format: "es",
  },
});
